CREATE TABLE users (
  user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR2(120) NOT NULL,
  email VARCHAR2(255) NOT NULL UNIQUE,
  password_hash VARCHAR2(255) NOT NULL,
  role VARCHAR2(30) NOT NULL,
  phone_number VARCHAR2(20),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE events (
  event_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organizer_id NUMBER NOT NULL,
  title VARCHAR2(200) NOT NULL,
  event_type VARCHAR2(100) NOT NULL,
  department VARCHAR2(100) NOT NULL,
  event_date DATE NOT NULL,
  event_time VARCHAR2(20) NOT NULL,
  location VARCHAR2(255) NOT NULL,
  description CLOB,
  image_url CLOB,
  status VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_events_organizer FOREIGN KEY (organizer_id) REFERENCES users(user_id)
);

CREATE TABLE registrations (
  registration_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id NUMBER NOT NULL,
  user_id NUMBER NOT NULL,
  status VARCHAR2(30) DEFAULT 'REGISTERED' NOT NULL,
  registered_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_registrations_event FOREIGN KEY (event_id) REFERENCES events(event_id) ON DELETE CASCADE,
  CONSTRAINT fk_registrations_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
  CONSTRAINT uq_event_user UNIQUE (event_id, user_id)
);

CREATE INDEX idx_events_organizer_id ON events(organizer_id);
CREATE INDEX idx_registrations_event_id ON registrations(event_id);
CREATE INDEX idx_registrations_user_id ON registrations(user_id);